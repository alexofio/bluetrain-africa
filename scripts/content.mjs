/**
 * Website content loader — reads published content from the Bluetrain Portal (Website Content).
 *
 * Runs before `npm run dev` and `npm run build`. Fetches the portal's public, read-only API:
 *   /api/public/content/informed      → Bluetrain Informed articles
 *   /api/public/content/case-studies  → case studies ("Turning strategy into execution")
 *   /api/public/content/clients       → the client wall (logos only where the client gave permission)
 *   /api/public/content/redirects     → old article/case-study addresses → new ones (301)
 * and writes src/content/informed.posts.generated.js and src/content/cms.generated.js.
 *
 * If the portal can't be reached, or returns zero articles, the build STOPS: Cloudflare then keeps the
 * live site on its previous version instead of publishing an empty one.
 * PORTAL_URL overrides the portal address (e.g. http://127.0.0.1:8787 for a local portal).
 *
 * The old Markdown files in content/informed/ are no longer read; they stay in the repo until the
 * new path has published live, so reverting this commit brings the old site back.
 */
import { writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url).pathname;
const PORTAL = (process.env.PORTAL_URL || "https://portal.bluetrain.africa").replace(/\/$/, "");

const CATEGORIES = ["strategy", "performance", "insights", "influence", "experiences", "technology", "news"];
const MARKETS = ["TZ", "KE", "ZA", "ZM", "AF"];
const FORMATS = ["news", "analysis", "guide"];

function stop(msg) {
  console.error(`\nBluetrain content — build stopped: ${msg}\nThe live site keeps its previous version.\n`);
  process.exit(1);
}

async function get(name) {
  let res;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      res = await fetch(`${PORTAL}/api/public/content/${name}`, { headers: { Accept: "application/json", "User-Agent": "bluetrain-africa-build" }, signal: AbortSignal.timeout(20000) });
      if (res.ok) return await res.json();
    } catch (e) { if (attempt === 3) stop(`the portal couldn't be reached for ${name} (${e.message}).`); }
    await new Promise((r) => setTimeout(r, 1500 * attempt));
  }
  stop(`the portal answered ${res?.status} for ${name}.`);
}

const [informed, cases, clients, redirects] = await Promise.all([get("informed"), get("case-studies"), get("clients"), get("redirects")]);
const posts = informed.items || [];
if (!posts.length) stop("the portal returned zero Informed articles.");

// Sanity checks: a malformed item stops the build rather than breaking a page.
const errors = [];
for (const p of posts) {
  const f = (m) => errors.push(`Informed "${p.slug}": ${m}`);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(p.slug || "")) f("bad address");
  if (!p.title) f("missing title");
  if (!p.standfirst) f("missing summary");
  if (!/^\d{4}-\d{2}-\d{2}$/.test(p.date || "")) f("missing date");
  if (!CATEGORIES.includes(p.category)) f(`unknown category ${p.category}`);
  if (!FORMATS.includes(p.format)) f(`unknown format ${p.format}`);
  if (!Array.isArray(p.body)) f("missing body");
  p.markets = (p.markets || []).filter((m) => MARKETS.includes(m));
  if (!p.markets.length) p.markets = ["AF"];
}
for (const c of cases.items || []) if (!c.slug || !c.title) errors.push(`Case study "${c.slug}": missing address or title`);
if (errors.length) stop("\n  " + errors.join("\n  "));

// Links to pages that aren't published (or were unpublished after this item went live) keep their text, lose the link.
const live = new Set([...posts.map((p) => `/informed/${p.slug}`), ...(cases.items || []).map((c) => `/work/${c.slug}`)]);
const fixLinks = (html) => String(html).replace(/<a href="(\/(?:informed|work)\/[\w-]+)"[^>]*>([\s\S]*?)<\/a>/g, (m, href, text) => (live.has(href) ? m : text));
const walk = (v) => (typeof v === "string" ? fixLinks(v) : Array.isArray(v) ? v.map(walk) : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)])) : v);
for (const p of posts) { p.body = walk(p.body); if (p.sw?.body) p.sw.body = walk(p.sw.body); }
for (const c of cases.items || []) { c.body = walk(c.body || []); if (c.sw?.body) c.sw.body = walk(c.sw.body); }

posts.sort((a, b) => b.date.localeCompare(a.date));
const version = Math.max(informed.version || 0, cases.version || 0, clients.version || 0, redirects.version || 0);

writeFileSync(ROOT + "src/content/informed.posts.generated.js",
  `// GENERATED by scripts/content.mjs from the Bluetrain Portal (content version ${version}) — do not edit by hand.\nexport default ${JSON.stringify(posts, null, 1)};\n`);
writeFileSync(ROOT + "src/content/cms.generated.js",
  `// GENERATED by scripts/content.mjs from the Bluetrain Portal — do not edit by hand.\n` +
  `export const version = ${version};\n` +
  `export const clients = ${JSON.stringify(clients.items || [], null, 1)};\n` +
  `export const industries = ${JSON.stringify(clients.industries || [], null, 1)};\n` +
  `export const caseStudies = ${JSON.stringify(cases.items || [], null, 1)};\n` +
  `export const redirects = ${JSON.stringify(redirects.items || [], null, 1)};\n`);
console.log(`content: ${posts.length} Informed articles, ${(cases.items || []).length} case studies, ${(clients.items || []).length} clients, ${(redirects.items || []).length} redirects (version ${version}, from ${PORTAL})`);
